
import logging
import os
import tempfile
import uuid
from pathlib import Path

from flask import Flask, jsonify, request, send_from_directory
from werkzeug.exceptions import HTTPException, RequestEntityTooLarge
from werkzeug.utils import secure_filename


ALLOWED_EXTENSIONS = {
    "txt", "pdf", "png", "jpg", "jpeg", "gif", "csv", "json"
}
MAX_FILE_SIZE = 16 * 1024 * 1024  # 16 MB


def create_app():
    app = Flask(__name__)

    app.config["UPLOAD_FOLDER"] = Path(
        os.environ.get("UPLOAD_FOLDER", "uploads")
    ).resolve()
    app.config["MAX_CONTENT_LENGTH"] = MAX_FILE_SIZE

    app.config["UPLOAD_FOLDER"].mkdir(
        parents=True,
        exist_ok=True
    )

    logging.basicConfig(level=logging.INFO)
    logger = logging.getLogger(__name__)

    def allowed_file(filename):
        return (
            "." in filename
            and filename.rsplit(".", 1)[1].lower()
            in ALLOWED_EXTENSIONS
        )

    @app.errorhandler(RequestEntityTooLarge)
    def handle_large_file(error):
        return jsonify({
            "error": "File exceeds the maximum allowed size of 16 MB."
        }), 413

    @app.errorhandler(HTTPException)
    def handle_http_error(error):
        return jsonify({
            "error": error.description
        }), error.code

    @app.errorhandler(Exception)
    def handle_unexpected_error(error):
        logger.exception("Unexpected server error")
        return jsonify({
            "error": "An internal server error occurred."
        }), 500

    @app.post("/upload")
    def upload_file():
        if "file" not in request.files:
            return jsonify({
                "error": "No file was provided."
            }), 400

        file = request.files["file"]

        if not file.filename:
            return jsonify({
                "error": "No file was selected."
            }), 400

        filename = secure_filename(file.filename)

        if not filename or not allowed_file(filename):
            return jsonify({
                "error": "Invalid filename or unsupported file type."
            }), 400

        extension = filename.rsplit(".", 1)[1].lower()

        # Generate a unique server-side filename to prevent
        # collisions and avoid exposing client filenames.
        stored_filename = f"{uuid.uuid4().hex}.{extension}"

        upload_directory = app.config["UPLOAD_FOLDER"]
        temporary_path = None

        try:
            # Write to a temporary file first so incomplete
            # uploads are not exposed as completed files.
            with tempfile.NamedTemporaryFile(
                mode="wb",
                dir=upload_directory,
                prefix=".upload_",
                delete=False
            ) as temporary_file:
                temporary_path = Path(temporary_file.name)

                while True:
                    chunk = file.stream.read(1024 * 1024)

                    if not chunk:
                        break

                    temporary_file.write(chunk)

            destination = upload_directory / stored_filename

            # Atomically move the completed file into place.
            os.replace(temporary_path, destination)

        except OSError:
            logger.exception("Failed to save uploaded file")

            return jsonify({
                "error": "Unable to save the uploaded file."
            }), 500

        finally:
            if temporary_path is not None:
                temporary_path.unlink(missing_ok=True)

        logger.info("File uploaded successfully: %s", stored_filename)

        return jsonify({
            "message": "File uploaded successfully.",
            "filename": stored_filename,
            "download_url": f"/download/{stored_filename}"
        }), 201

    @app.get("/download/<filename>")
    def download_file(filename):
        # Only filenames generated by this application are valid.
        name, separator, extension = filename.rpartition(".")

        if (
            not separator
            or len(name) != 32
            or any(char not in "0123456789abcdef" for char in name)
            or extension not in ALLOWED_EXTENSIONS
        ):
            return jsonify({
                "error": "Invalid file identifier."
            }), 400

        upload_directory = app.config["UPLOAD_FOLDER"]

        return send_from_directory(
            directory=upload_directory,
            path=filename,
            as_attachment=True
        )

    return app


app = create_app()


if __name__ == "__main__":
    app.run(
        host="127.0.0.1",
        port=5000,
        debug=False
    )
